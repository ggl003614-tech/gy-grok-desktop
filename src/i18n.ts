const tables: Record<Locale, Dict> = { zh, en };

let current: Locale = "zh";
const listeners = new Set<() => void>();

export function getLocale() {
  return current;
}

export function t(key: string, vars?: Record<string, string | number>) {
  const table = tables[current];
  let text = table[key] ?? tables.zh[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function subscribeLocale(listener: () => void) {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

export function setLocale(next: Locale) {
  if (next !== "zh" && next !== "en") return;
  current = next;
  if (typeof document !== "undefined") {
    document.documentElement.lang = next === "en" ? "en" : "zh-CN";
  }
  try {
    window.localStorage.setItem("grok-desk.locale", next);
  } catch {
    // ignore
  }
  for (const listener of listeners) listener();
}

export function detectLocale(): Locale {
  try {
    const stored = window.localStorage.getItem("grok-desk.locale");
    if (stored === "en" || stored === "zh") return stored;
  } catch {
    // ignore
  }
  if (typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("en")) {
    return "en";
  }
  return "zh";
}

export function initLocale(preferred?: Locale) {
  current = preferred ?? detectLocale();
  if (typeof document !== "undefined") {
    document.documentElement.lang = current === "en" ? "en" : "zh-CN";
  }
}

export function useT() {
  const [, setTick] = useState(0);
  useEffect(() => subscribeLocale(() => setTick((value) => value + 1)), []);
  return t;
}

export function useLocale() {
  const [, setTick] = useState(0);
  useEffect(() => subscribeLocale(() => setTick((value) => value + 1)), []);
  return { locale: getLocale(), setLocale, t };
}

export const I18N_KEYS = { zh, en };
